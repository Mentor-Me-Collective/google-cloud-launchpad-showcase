export function useCopy() {
  const storedLocale = useSettingsStore((state) => state.locale);
  const locale: Locale = storedLocale === 'en' ? 'en' : 'es';
  return {
    locale,
    ...COPY[locale],
    t: (key: string, values?: InterpolationValues) => translate(locale, key, values),
  };
}

export function copyFor(locale: Locale) {
  const safeLocale: Locale = locale === 'en' ? 'en' : 'es';
  return {
    locale: safeLocale,
    ...COPY[safeLocale],
    t: (key: string, values?: InterpolationValues) => translate(safeLocale, key, values),
  };
}

export function translate(locale: Locale, key: string, values?: InterpolationValues): string {
  const safeLocale = locale === 'en' ? 'en' : 'es';
  const reverseSpanish =
    safeLocale === 'en'
      ? Object.entries(UI_COPY.es).find(([, spanish]) => spanish === key)?.[0]
      : undefined;
  const template = UI_COPY[safeLocale][key] ?? reverseSpanish ?? key;
  return values
    ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
    : template;
}

type Copy = { t: (key: string, values?: InterpolationValues) => string };

/** "1 student" / "3 students", translated. */
export function studentsLabel(copy: Copy, count: number): string {
  return count === 1 ? copy.t('1 student') : copy.t('{count} students', { count });
}

/** "1 mission" / "3 missions", translated. */
export function missionsLabel(copy: Copy, count: number): string {
  return count === 1 ? copy.t('1 mission') : copy.t('{count} missions', { count });
}
